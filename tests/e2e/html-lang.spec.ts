import { test, expect } from '@playwright/test';

/**
 * `<html lang>` іде за вибраною мовою (I18N-v8 § 5.2, § 7.2; ACCESSIBILITY-v8,
 * анти-патерни HIGH).
 *
 * Це не косметика: скрінрідер обирає голос і правила вимови саме за цим
 * атрибутом, тож англійський текст під `lang="uk"` читається нерозбірливо.
 *
 * ЧОМУ ЦЕЙ ТЕСТ ІСНУЄ, ХОЧА КОД ПРАВИЛЬНИЙ. У самому репозиторії немає жодного
 * рядка, який виставляв би цей атрибут: `app.html` оголошує `lang="uk"`
 * статично, і на цьому все. Атрибут оновлює `svelte-i18n` — його підписка на
 * `locale` робить `documentElement.setAttribute('lang', …)` усередині
 * бібліотеки. Тобто вимога виконується побічним ефектом залежності, і зникне
 * вона так само тихо: від оновлення мажора, від переїзду на іншу бібліотеку
 * i18n, від власної обгортки над `locale`. Нічого в `src/` про це не скаже.
 *
 * Це рівно той випадок, для якого канон вимагає перевірку, а не прочитання
 * коду: правило без перевірки — побажання (AI-AGENT-PITFALLS-v8 § 6).
 *
 * Перевірку прогнано зворотним експериментом (§ 1.1): тимчасове прибирання
 * підписки в `svelte-i18n` лишає першу асерцію зеленою (там `lang="uk"` із
 * `app.html`) і валить другу — тобто тест ловить саме зміну, а не наявність
 * атрибута.
 */
test('перемикання мови оновлює <html lang>', async ({ page }) => {
	await page.goto('/');

	// Канарка: без неї зламаний застосунок (порожня сторінка) дав би
	// `lang="uk"` із самого `app.html` і зелений тест.
	//
	// 20 c, а не типові 5: тест ходить по dev-серверу, який компілює модулі на
	// перший запит. На холодному кеші Vite головне меню з'являється пізніше за
	// п'яту секунду, і перевірка падала там, де порушення немає — плаваючий
	// гейт, на який швидко перестають дивитися (CODE-QUALITY-v8 § 6.4.2).
	await expect(page.getByTestId('top-language-btn')).toBeVisible({ timeout: 20_000 });
	await expect(page.locator('html')).toHaveAttribute('lang', 'uk');

	await page.getByTestId('top-language-btn').click();
	await page.getByTestId('lang-option-en').click();

	await expect(page.locator('html')).toHaveAttribute('lang', 'en');
});
