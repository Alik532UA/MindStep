// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * ЖИВА ПІДПИСКА, ЯКУ НІХТО НЕ КЛИЧЕ, — це не запас, а мертвий код.
 *
 * ## Чому цей файл існує
 *
 * Двічі в цьому проєкті готовий код виявився недосяжним, і обидва рази це
 * виглядало як відсутня функція, а не як забутий виклик:
 *
 *  * `authService.init()` не мав жодного виклику — разом із ним не працювали
 *    злиття місцевого рекорду з хмарним і жива підписка на свій профіль;
 *  * `roomService.subscribeToPublicRooms()` лежав готовим, а лобі читало перелік
 *    одноразово на монтуванні. Скарга автора звучала як «список кімнат
 *    оновлюється тільки якщо натиснути кнопку оновити».
 *
 * Спільна ознака в обох: метод є, дописаний і навіть прокомментований, але жоден
 * екран його не кличе. Компілятор про це не скаже нічого — публічний метод класу
 * без викликів для нього норма.
 *
 * ## Межа перевірки
 *
 * Перевіряється ДОСЯЖНІСТЬ, а не поведінка: що назву методу згадано хоч десь поза
 * самим сервісом. Поведінку живого переліку перевіряє
 * `services/roomService.spec.ts`, а те, що він справді оживає в браузері,
 * заміряно вдвох на емуляторі: кімната з'явилася й зникла в сусідньому вікні без
 * жодного натиску «Оновити».
 */

const SERVICE = 'src/lib/services/roomService.ts';

function sources(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) {
			sources(full, out);
		} else if (/\.(ts|svelte)$/.test(entry)) {
			// Слеші не нормалізуємо: файли читаються за тим самим шляхом, яким прийшли.
			out.push(full);
		}
	}
	return out;
}

describe('живі підписки досяжні', () => {
	const service = readFileSync(SERVICE, 'utf8');
	const subscribers = [...service.matchAll(/^\s{4}(subscribe[A-Za-z]*)\s*\(/gm)].map((m) => m[1]);

	it('перевірка жива: у сервісі є хоч одна підписка', () => {
		expect(subscribers.length).toBeGreaterThan(0);
	});

	it('кожну підписку хтось кличе', () => {
		/*
		 * КЛИЧЕ — ЦЕ ЕКРАН АБО КОНТРОЛЕР, а не сусідній сервіс і не власний тест.
		 *
		 * Перша редакція цієї перевірки лишалася зеленою після того, як лобі
		 * повернули до одноразового читання: назву методу згадував його ж
		 * `roomService.spec.ts`, і цього виявилося достатньо. Підписка, до якої
		 * доходить лише власний тест, так само недосяжна для людини — саме те, що
		 * перевірка мусила ловити. Шар нижче (`services/room/*`) виключений з тієї
		 * самої причини: там лежить реалізація з тією ж назвою.
		 */
		const others = sources('src').filter(
			(file) => !/\.(spec|test)\.ts$/.test(file) && !file.includes('services')
		);
		const text = others.map((file) => readFileSync(file, 'utf8')).join(String.fromCharCode(10));

		/*
		 * Шукається ВИКЛИК, а не назва: коментарі поруч називають ці методи, і
		 * перевірка на просту назву лишалася б зеленою, якби код прибрали, а
		 * пояснення — ні. Перевірено: саме так вона й пропустила першу спробу
		 * зламати її.
		 */
		const orphans = subscribers.filter((name) => !text.includes(`${name}(`));
		expect(
			orphans,
			`підписка без жодного виклику — екран її не отримає: ${orphans.join(', ')}`
		).toEqual([]);
	});
});
