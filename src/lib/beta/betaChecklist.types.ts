/**
 * Типи чеклиста бета-тестування (BETA-CHECKLIST-v8).
 *
 * Ключове рішення файлу: половину інваріантів канону тут виконує ТИП, а не
 * перевірка. Канон § 2.4 вимагає «`test` обов'язковий для `covered`,
 * заборонений для решти» — це правило можна написати тестом, а можна зробити
 * невимовним. Другий шлях кращий: тест повідомляє про порушення після того, як
 * його зробили, тип не дає його зробити.
 *
 * Так само з мовами: `Localized` вимагає обидві. У чужому джерелі, з якого
 * канон узяв форму пункта, мови лежали двома деревами файлів — і знадобилося
 * окреме правило про міжмовну відповідність плюс скрипт, що його звіряє. Тут
 * пункт без англійського тексту не збереться.
 */

/** Обидві мови обов'язкові. Решта мов інтерфейсу показує англійський. */
export interface Localized {
	uk: string;
	en: string;
}

/**
 * Чи може пункт перевірити машина.
 *
 * - `manual` — око, палець, друга людина, справжній телефон;
 * - `testable` — покрити можна, покриття НЕМА. Це готовий беклог тестів;
 * - `covered` — покрито, файл названий. Лишається в списку як контрольна
 *   група: помилка тут — звіт про дефект ТЕСТА, а не гри.
 */
export type Coverage = 'manual' | 'testable' | 'covered';

interface BetaCheckBase {
	/**
	 * Стабільний назавжди — це ключ прогресу у сховищі. Перейменувати
	 * `online_3` означає стерти людині позначку. Нові пункти ДОПИСУЮТЬСЯ з
	 * новим номером; наявні не перенумеровуються навіть коли порядок змінився.
	 */
	id: string;
	category: Localized;
	text: Localized;
	/**
	 * Локатор елемента, який пункт просить натиснути. Обов'язковий там, де в
	 * тексті є «натисн» — інакше пункт неперевірний за побудовою (§ 5.3).
	 */
	testid?: string;
	/**
	 * Перевірка МЕЖІ: «не мусить». Найдорожчі дефекти тихі — ліміт, що
	 * перестав діяти, виглядає точно так само, як ліміт, що діє (§ 2.3).
	 */
	negative?: true;
}

/** Покритий пункт мусить назвати файл тесту — існування перевіряє § 5.2. */
interface CoveredCheck extends BetaCheckBase {
	coverage: 'covered';
	test: string;
}

/** Непокритий пункт НЕ має права називати тест: одне з двох тоді неправда. */
interface UncoveredCheck extends BetaCheckBase {
	coverage: 'manual' | 'testable';
	test?: never;
}

export type BetaCheck = CoveredCheck | UncoveredCheck;

/**
 * Вкладка називає МАРШРУТИ, а не гру словами.
 *
 * Причина в § 5.1: перелік маршрутів у проєкті вже існує (це дерево
 * `src/routes`), і його ніхто не забуде поповнити — без нього сторінки просто
 * не буде. Другий список, який тримають узгодженим руками, розійдеться з
 * першим на першому ж новому режимі.
 */
export interface BetaTab {
	id: string;
	title: Localized;
	routes: readonly string[];
}

/** Чотири стани відповіді: відсутність позначки — і є «не перевірено». */
export type BetaVote = 'fail' | 'weird' | 'ok';

export interface BetaMark {
	vote: BetaVote;
	/**
	 * Версія збірки, на якій поставили. Позначка з іншої версії не зникає —
	 * вона все ще щось означає, — але підписана й не рахується в «зроблено на
	 * цій». Без цього список стає звітом про минуле, який читають як звіт про
	 * теперішнє (§ 3.1).
	 */
	version: string;
}

/** Порядок показу рівнів. Не косметика — див. § 3. */
export const COVERAGE_ORDER: readonly Coverage[] = ['manual', 'testable', 'covered'];
