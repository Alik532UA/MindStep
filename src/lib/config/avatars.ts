/**
 * АВАТАР — КОРОТКИЙ РЯДОК `значок:колір`, а не картинка.
 *
 * ## Чому не зображення
 *
 * Зберігати його було б ніде: Storage у проєкті немає, а заводити його заради
 * підпису в списку — це і правила доступу до файлів, і межа розміру, і чистка
 * покинутого, і CSP на новий origin. У публічному профілі ж лежать самі поля, і
 * `cat:blue` важить дев'ять байтів, не додаючи жодного нового механізму.
 *
 * Форма та сама, що в обох сусідніх проєктах: `Slovko` пише
 * `internal:{значок}:{колір}` у поле `photoURL`, `VetCrewGames` — `значок:колір`
 * у профіль. Тут узято другу, коротшу: поле своє, і префікс ні від чого не
 * відрізняє.
 *
 * ## Чому два незалежні виміри, а не один список
 *
 * Чотирнадцять значків і вісім кольорів дають 112 різних підписів вісьмома
 * плюс чотирнадцятьма кнопками. Готовий список із 112 картинок займав би екран
 * прокруткою й не давав би нічого зверху.
 *
 * ## Значки — лише `lucide-svelte`
 *
 * Системні емодзі в UI заборонені (той самий рядок є і в цьому AGENTS.md, і в
 * сусідів): на Windows замість прапора стоять дві літери, і те саме буває з
 * тваринами.
 *
 * ## Межа довжини
 *
 * Найдовша пара зараз `rabbit:violet` (13), а 24 лишає місце на довшу назву.
 * Межа тут не косметична: взірець `[a-z]+:[a-z]+` сам собою пропустив би
 * мегабайт літер.
 */

/**
 * Значки. Порядок — той, у якому вони стоять у виборі, і він не випадковий:
 * спершу людина (типовий), далі тварини, далі знаки.
 */
export const AVATAR_ICONS = [
	'user',
	'cat',
	'dog',
	'rabbit',
	'bird',
	'fish',
	'snail',
	'turtle',
	'bug',
	'smile',
	'star',
	'heart',
	'zap',
	'target'
] as const;

/**
 * Кольори тла — ІМЕНАМИ, а не значеннями.
 *
 * У рядок їде імʼя (`cat:blue`), а не `#1d4ed8`, і причина не в довжині: колір
 * мусить лишитися тим самим після зміни палітри й мусить бути перевірним. Самі
 * значення живуть змінними `--avatar-*` у стилях компонента, тобто в одному
 * місці на всі теми.
 *
 * Палітра НЕ залежить від теми, і це рішення: аватар відрізняє людину, тож він
 * мусить виглядати однаково в мене й у неї. Видимість плитки на будь-якій
 * панелі дає тонка рамка з кольору тексту — той самий прийом, що у `Flag`.
 */
export const AVATAR_COLORS = [
	'red',
	'orange',
	'green',
	'teal',
	'blue',
	'violet',
	'pink',
	'slate'
] as const;

export type AvatarIcon = (typeof AVATAR_ICONS)[number];
export type AvatarColor = (typeof AVATAR_COLORS)[number];

/** Аватар, розібраний на дві частини. */
export interface AvatarLook {
	icon: AvatarIcon;
	color: AvatarColor;
}

/**
 * Типовий аватар. Він же відповідь на «поле відсутнє» і на «поле зіпсоване»:
 * порожньої плитки в списку не буває, бо порожнеча читалася б як дефект.
 */
export const DEFAULT_AVATAR = 'user:teal';

/** Межа довжини рядка. */
export const AVATAR_MAX = 24;

/** Взірець форми. */
const SHAPE = /^[a-z]+:[a-z]+$/;

/**
 * Чи це наш аватар — тобто відома пара з відомих списків.
 *
 * Перевіряється НЕ лише форма: `dragon:gold` формі відповідає, а намалювати
 * його нічим. Невідоме значення означає або чужу руку, або наш власний дефект,
 * і в обох випадках правильна відповідь — типовий аватар, а не порожнє місце.
 */
export function isAvatar(value: unknown): value is string {
	if (typeof value !== 'string' || value.length > AVATAR_MAX || !SHAPE.test(value)) return false;
	const [icon, color] = value.split(':');
	return (
		(AVATAR_ICONS as readonly string[]).includes(icon) &&
		(AVATAR_COLORS as readonly string[]).includes(color)
	);
}

/** Розібрати аватар. Невідоме — типовий, а не виняток: це підпис, а не стан гри. */
export function parseAvatar(value: string | null | undefined): AvatarLook {
	const [icon, color] = (isAvatar(value) ? value : DEFAULT_AVATAR).split(':');
	return { icon: icon as AvatarIcon, color: color as AvatarColor };
}

/** Зібрати аватар у рядок для запису. */
export function formatAvatar(icon: AvatarIcon, color: AvatarColor): string {
	return `${icon}:${color}`;
}
