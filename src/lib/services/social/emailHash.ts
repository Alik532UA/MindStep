/**
 * Хеш пошти для пошуку людей.
 *
 * **Правил рівня поля у Firestore не існує.** Дозвіл читати документ означає
 * дозвіл читати ВСІ його поля, тож приватне значення в публічному документі
 * приватним не стає — воно просто не показане в інтерфейсі
 * (CLOUD-DATABASE-v8 § 4.5).
 *
 * У сусідньому `Slovko` в `profiles/{uid}` лежала пошта ВІДКРИТИМ ТЕКСТОМ, а
 * колекція читається для пошуку; приватність трималася умовою запиту
 * `where("privacy.showInSearch","==",true)` — тобто фільтром, а не контролем
 * доступу: той самий запит без `where` повертав усе. Тут обидві половини стоять
 * інакше з першого дня: пошта — хешем, а умову згоди вимагає САМЕ ПРАВИЛО
 * (`firestore.rules`, `match /profiles/{uid}` → `allow list`), тож запит без неї
 * Firestore відкидає цілком.
 *
 * **Чому саме хеш, а не «прибрати перелічування».** Пошук тут працює лише за
 * ТОЧНИМ збігом пошти (пошук за іменем вимкнено окремо, з підпису в
 * `FriendsService`). Точний збіг однаково добре працює й по хешу — а витягти з
 * колекції адресу стає неможливо. Заборона перелічування була б слабшою: документ
 * усе одно віддається цілком тому, хто знає ідентифікатор.
 *
 * **Чому без солі.** Сіль зробила б хеш непорівнюваним між користувачами, а
 * пошук за точним збігом саме на порівнянні й стоїть. Це свідомий компроміс і
 * його межі варто назвати прямо: хеш захищає від масового вивантаження адрес, а
 * не від перевірки конкретної здогадки. Хто вже знає адресу, той підтвердить її
 * наявність — але це рівно те, що вміє й сама форма пошуку.
 */

/** Нормалізація — щоб `  Ivan@Example.COM ` і `ivan@example.com` дали той самий хеш. */
const normalizeEmail = (email: string): string => email.trim().toLowerCase();

/**
 * SHA-256 від нормалізованої пошти, у шістнадцятковому вигляді.
 *
 * `crypto.subtle` доступний лише в захищеному контексті (https або localhost).
 * Повертає `null`, коли його немає: пошук тоді не знайде нікого, і це краще, ніж
 * тихо записати адресу відкритим текстом у публічну колекцію.
 */
export async function hashEmail(email: string | null | undefined): Promise<string | null> {
	if (!email) return null;
	const subtle = globalThis.crypto?.subtle;
	if (!subtle) return null;

	const data = new TextEncoder().encode(normalizeEmail(email));
	const digest = await subtle.digest("SHA-256", data);
	return Array.from(new Uint8Array(digest))
		.map((byte) => byte.toString(16).padStart(2, "0"))
		.join("");
}
