import type { MoveDirectionType } from '$lib/models/Piece';
import type { Player } from '$lib/models/player';
import type { GameSettingsState } from '$lib/stores/gameSettingsTypes';

/**
 * Конверт онлайн-партії: опис + ЖУРНАЛ ХОДІВ.
 *
 * Форма даних у Firestore:
 *
 * ```
 * rooms/{roomId}                        — кімната: склад, статус, налаштування
 * rooms/{roomId}.match                  — опис партії: { seed, segment, boardSize, players, settings }
 * rooms/{roomId}/moves/{segment}-{seq}  — ОДИН ХІД: лише СТВОРИТИ, назавжди
 * rooms/{roomId}/votes/{playerId}       — голос гравця, і кінець партії від того, хто його оголосив
 * ```
 *
 * Присутність тут НЕ лежить: вона живе в RTDB (`/status/{roomId}/{uid}`), бо її
 * тримає `onDisconnect`. Дзеркало у Firestore було й прибране — його писав сам
 * клієнт, тобто саме тоді, коли писати вже нікому (§ 5.2).
 *
 * **Кожен запис має ВЛАСНИКА, і саме це дозволяє звузити правила.** Опис партії
 * пише лише господар; хід — лише той, хто його зробив, і лише один раз; голос —
 * лише сам гравець у документ, названий його ідентифікатором. Доти вся партія
 * лежала в одному документі, який писали обидва: власника не було, тож єдиний
 * дозвіл, що не ламав гру, — `allow write: if true`.
 *
 * **Стан партії тут не зберігається взагалі.** Він обчислюється перепрогоном
 * журналу (`matchReplay.ts`). Один документ на хід замість перезапису всього
 * стану знімає й межу «~1 запис/с на документ», і взаємне перетирання, і
 * потребу виводити «що нового» порівнянням довжин.
 */

/** Один хід у журналі. Ключ документа — `{segment}-{seq}`. */
export interface MatchMove {
	/**
	 * Номер ВІДРІЗКА партії, у якому зроблено хід.
	 *
	 * Замінює стирання журналу. Доти «нова партія в тій самій кімнаті» означала
	 * прочитати всі ходи й видалити їх батчем — і це давало три дефекти одразу:
	 * платню за кожен хід удруге, межу батча 500 (партія довша за 499 ходів не
	 * перезапускалася) і `get()` на кімнату в правилі видалення, по одному на
	 * кожен хід при межі 20 звернень на батч.
	 *
	 * Причина всіх трьох одна: видалення журналу суперечить самій моделі журналу.
	 * Тепер відрізок — це новий сегмент, ходи лишаються назавжди, а перепрогін
	 * бере лише ті, чий `segment` збігається з описом партії
	 * (CLOUD-DATABASE-v8 § 8.7).
	 */
	segment: number;
	/** Порядок усередині відрізка. Разом із `segment` дає ключ документа. */
	seq: number;
	/** Хто зробив — ідентифікатор гравця в кімнаті. Перевіряється правилом. */
	by: string;
	direction: MoveDirectionType;
	distance: number;
	/**
	 * Коли зробив — СЕРВЕРНИМ часом.
	 *
	 * Не для гри: стан партії від часу не залежить і залежати не має. Потрібне
	 * для діагностики й для того, щоб «хто перший зайняв номер» можна було
	 * встановити після факту, а не вгадувати.
	 */
	at?: number;
}

/** Опис партії. Усе, з чого перепрогін відтворює стан. */
export interface MatchSetup {
	/**
	 * Зерно партії. Одне число замість усієї початкової розкладки — і саме воно
	 * робить дошку однаковою в усіх без жодного обміну станом.
	 */
	seed: number;
	/**
	 * Номер поточного відрізка. Ходи інших відрізків перепрогін не бачить.
	 *
	 * Необовʼязкове в ТИПІ й обовʼязкове в новій партії: кімнати, створені до
	 * появи сегментів, читаються далі — відсутність трактується як нуль.
	 */
	segment?: number;
	boardSize: number;
	/**
	 * Склад НА МОМЕНТ ПОЧАТКУ, у зафіксованому порядку.
	 *
	 * Копія, а не посилання на список кімнати: черга ходів рахується з цього
	 * порядку, тож зміна складу посеред партії не має права його зсунути. Той, хто
	 * зайшов після початку, стає глядачем до наступної партії.
	 */
	players: Player[];
	/**
	 * ХТО СИДИТЬ НА КОЖНОМУ МІСЦІ — за тим самим іменем, яким підписано хід.
	 *
	 * Індекси збігаються з `players`. Здається дублюванням, але ним не є:
	 * `Player.id` — це номер місця для рушія (1, 2, …), а хід підписано `auth.uid`,
	 * бо правило `moves` вимагає `by == request.auth.uid` і інакше підпис нічого не
	 * вартий. Тобто в описі партії лежали НОМЕРИ МІСЦЬ, а в журналі — ЛЮДИ, і
	 * зіставити їх не було чим.
	 *
	 * Заміряно 2026-08-25 на живій кімнаті: `byId` будувався з `String(player.id)`,
	 * тобто з ключами «1» і «2», а `move.by` був `fuVEIXPINgxC6kU0yqV4VvEkjRfo` —
	 * і перепрогін відкидав УСІ ходи до одного. Ходи при цьому справно лягали в
	 * базу, підписка їх приносила, помилок не було ЖОДНОЇ: дошка просто не рухалася.
	 *
	 * Необовʼязкове в типі заради двох випадків: кімнат, створених до цієї правки,
	 * і памʼятного журналу в перевірках, де місце й людина — одне й те саме.
	 */
	playerIds?: string[];
	/** Налаштування, від яких залежать правила ходу. Міняє лише господар у лобі. */
	settings: Partial<GameSettingsState>;
	/** Коли партію почали — серверним часом. */
	startedAt?: number;

	/*
	 * --- Три поля нижче існують заради ОДНОГО сценарію: «продовжити гру». ---
	 *
	 * Коли гравцеві немає куди ходити, решта голосує. Якщо більшість за
	 * продовження, лічильники відвідувань обнуляються, а фігура лишається там,
	 * де стоїть, рахунок зберігається, і черга йде далі.
	 *
	 * У моделі журналу це не «правка стану», а НОВИЙ ВІДРІЗОК: опис переписується
	 * з наступним `segment`, а старі ходи лишаються в журналі — просто до цього
	 * відрізка вже не належать. Без цих полів відрізок починався б із клітинки від
	 * зерна, з нульовим рахунком і з першого гравця — тобто «продовжити» означало
	 * б «почати спочатку».
	 */

	/** Звідки починається відрізок. Без значення — клітинка від зерна. */
	startCell?: { row: number; col: number };
	/** Чия черга на початку відрізка. Без значення — перший у складі. */
	startTurnIndex?: number;
}

/** Знімок партії з транспорту: опис і впорядкований журнал. */
export interface MatchSnapshot {
	/** `null` — партія ще не почалася: господар не написав опис. */
	setup: MatchSetup | null;
	moves: MatchMove[];
}

/**
 * Транспорт партії. Дві реалізації: справжня база й підставна для тестів.
 *
 * Інтерфейс тут не для «гнучкості на майбутнє», а тому що інакше правила
 * онлайн-партії неперевірні: із живою базою кожна перевірка вимагала б мережі,
 * ключів і чужого часу — і шар синхронізації лишався б без жодного тесту, як і
 * було. Із підставним транспортом двоє учасників живуть в одному процесі, і
 * питання «обидва бачать те саме» стає звичайним `expect`.
 */
export interface MatchLog {
	/** Підписка на знімки. Повертає відписку. */
	watch(onSnapshot: (snapshot: MatchSnapshot) => void): () => void;

	/**
	 * Дописати хід.
	 *
	 * `false` означає, що номер уже зайнятий — тобто хтось зробив хід раніше, і
	 * ЦЕЙ хід не відбувся. Це не помилка: журнал і є правда.
	 */
	append(move: MatchMove): Promise<boolean>;

	/**
	 * Почати НОВИЙ ВІДРІЗОК партії. Дозволено господареві.
	 *
	 * Одним записом одного поля — і саме тому проміжку не існує в принципі. Доти
	 * це були опис плюс видалення всіх ходів батчем, тобто «нова партія» вимагала
	 * прочитати журнал, щоб його знищити, впиралася в межу батча 500 і тягла
	 * `get()` у правило видалення. Тепер старі ходи просто лишаються поза
	 * поточним сегментом (CLOUD-DATABASE-v8 § 8.6, § 8.7).
	 */
	start(setup: MatchSetup): Promise<void>;

	/** Відписатися й відпустити ресурси. */
	cleanup(): void;
}

/**
 * Ключ документа ходу: `{segment}-{seq}`, обидва вирівняні нулями.
 *
 * Вирівнювання — щоб лексикографічний порядок ключів дорівнював числовому: без
 * нього «10» стало б між «1» і «2». Сегмент теж вирівнюється, бо їх може стати
 * більше девʼяти за одну кімнату.
 */
export const moveKey = (segment: number, seq: number): string =>
	`${String(segment).padStart(3, '0')}-${String(seq).padStart(6, '0')}`;

/** Номер відрізка з опису партії. Кімнати старішої збірки його не мають. */
export const segmentOf = (setup: Pick<MatchSetup, 'segment'> | null): number =>
	setup?.segment ?? 0;

/**
 * Партія в памʼяті: той самий транспорт, тільки без мережі.
 *
 * Заразом це чесна модель обмежень справжньої бази: `append` відмовляє на
 * зайнятому номері рівно так, як відмовить правило «лише створити». Підставка,
 * добріша за оригінал, доводить не те, що треба.
 */
export class MemoryMatchLog implements MatchLog {
	#setup: MatchSetup | null = null;
	#moves: MatchMove[] = [];
	#listeners = new Set<(snapshot: MatchSnapshot) => void>();
	/** «Серверний» час. Не `Date.now()`: тест мусить керувати ним сам. */
	#now: number;

	constructor(setup: MatchSetup | null = null, startAt = 1_000_000) {
		this.#now = startAt;
		if (setup) this.#setup = { ...setup, startedAt: startAt };
	}

	/** Просунути «серверний» час. */
	tick(ms: number): number {
		this.#now += ms;
		return this.#now;
	}

	watch(onSnapshot: (snapshot: MatchSnapshot) => void): () => void {
		this.#listeners.add(onSnapshot);
		// Перший знімок — одразу: підписка мусить давати ПОТОЧНИЙ стан, а не лише
		// майбутні зміни. Інакше учасник, який зайшов посеред партії, сидів би з
		// порожньою дошкою до чийогось наступного ходу.
		onSnapshot(this.#snapshot());
		return () => this.#listeners.delete(onSnapshot);
	}

	async append(move: MatchMove): Promise<boolean> {
		/*
		 * `undefined` усередині ходу — помилка програмування, і тут вона кидає
		 * рівно так, як кидає запис у Firestore. Підставка, яка приймає більше за
		 * базу, ховає справжній дефект: хід зникає безслідно, а дошка чекає на те,
		 * чого не буде.
		 */
		for (const [key, value] of Object.entries(move)) {
			if (value === undefined && key !== 'at') throw new Error(`move.${key} is undefined`);
		}
		/*
		 * Зайнятий ключ — це пара (сегмент, номер), а не номер сам по собі: у
		 * справжній базі ключ документа саме такий, і номери починаються заново в
		 * кожному відрізку. Підставка, яка відмовляла б лише за номером, забороняла
		 * б перший хід нового відрізка.
		 */
		const taken = this.#moves.some(
			(existing) => existing.seq === move.seq && existing.segment === move.segment
		);
		if (taken) return false;
		this.#moves.push({ ...move, at: this.#now });
		this.#moves.sort((a, b) => a.segment - b.segment || a.seq - b.seq);
		this.#emit();
		return true;
	}

	async start(setup: MatchSetup): Promise<void> {
		/*
		 * Журнал НЕ стирається — так само, як у справжній базі: новий відрізок
		 * отримує наступний номер сегмента, а старі ходи лишаються назавжди. Раніше
		 * тут стояло `this.#moves = []`, і підставка була добріша за оригінал —
		 * тобто доводила не те, що треба (CLOUD-DATABASE-v8 § 8.5, § 8.7).
		 */
		this.#setup = { ...setup, segment: segmentOf(setup), startedAt: this.#now };
		this.#emit();
	}

	cleanup(): void {
		this.#listeners.clear();
	}

	get moves(): readonly MatchMove[] {
		return this.#moves;
	}

	#snapshot(): MatchSnapshot {
		// Копії, а не посилання: адаптер не має жодного права правити журнал «на
		// місці» — у справжній базі це неможливо.
		const segment = segmentOf(this.#setup);
		return {
			setup: this.#setup ? { ...this.#setup, players: this.#setup.players.map((p) => ({ ...p })) } : null,
			// Лише поточний відрізок: ходи попередніх лежать у журналі, але до стану
			// цієї партії не належать.
			moves: this.#moves.filter((move) => move.segment === segment).map((move) => ({ ...move }))
		};
	}

	#emit(): void {
		const snapshot = this.#snapshot();
		for (const listener of this.#listeners) listener(snapshot);
	}
}
