/**
 * «ПАРТІЯ ЗАВЕРШЕНА» — ОДНЕ ВИЗНАЧЕННЯ НА ВЕСЬ ОНЛАЙН.
 *
 * ## Навіщо окремий файл під один вираз
 *
 * Бо доти цих визначень було два, і вони розходилися саме в тому випадку, який
 * зламався. Скарга автора: один гравець натиснув «Грати ще раз», а другий побачив,
 * ніби суперник на мить пропав і повернувся, вікно результатів зникло, і далі він
 * стояв на екрані гри, у якій уже не можна грати.
 *
 * Складалося це так:
 *
 *  * `GameStateReconciler` вважав партію завершеною, поки в базі є спільна ознака
 *    `gameOver`. Перезапуск сусіда її чистить — і прапорець `uiState.isGameOver`
 *    ставав `false`;
 *  * `OnlinePresenceManager` питав ЛИШЕ той прапорець. Побачивши «партія триває, а
 *    суперника немає», він відкривав вікно перепідключення через `showModal`, і
 *    воно ВИТІСНЯЛО вікно результатів. Захист «не закривати результати» в
 *    реконсиляторі при цьому не спрацьовував: ніхто нічого не закривав.
 *
 * Тепер обидва питають це. Головне тут — `resultsOver`: це МІЙ результат, і він не
 * залежить від того, що сусід зробив зі своєю кімнатою.
 */
export interface FinishedView {
	/** Прапорець екрана. Його перемикає реконсилятор із сигналу з мережі. */
	uiOver: boolean;
	/** Мій власний результат. Живе доти, доки я сам його не закрию. */
	resultsOver: boolean;
	/** `data-testid` відкритого вікна, якщо якесь відкрите. */
	openModalTestId?: string | null;
}

/** Локатор вікна результатів. Той самий рядок, що в `modalService`. */
export const GAME_OVER_MODAL = 'game-over-modal';

/**
 * Чи завершена партія З МОГО ПОГЛЯДУ.
 *
 * Три джерела, і будь-якого досить. Третє — саме вікно: випадок, коли стан уже
 * скинули, а вікно ще стоїть, теж мусить читатися як «завершено», інакше сторож
 * присутності накриє результати за мить до їх закриття.
 */
export function isMatchFinished(view: FinishedView): boolean {
	return view.uiOver || view.resultsOver || view.openModalTestId === GAME_OVER_MODAL;
}

/**
 * Чи показуються МОЇ результати саме зараз.
 *
 * Окремо від `isMatchFinished`, бо відповідає на інше питання: не «чи завершено»,
 * а «чи стоїть на екрані те, що закриває лише людина». Від цього залежить, чи
 * можна гасити прапорець завершення й закривати вікна.
 */
export function isShowingResults(view: FinishedView): boolean {
	return view.resultsOver && view.openModalTestId === GAME_OVER_MODAL;
}
