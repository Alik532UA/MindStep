// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * ОНЛАЙН МУСИТЬ ПИТАТИ РУШІЙ — так само, як місцева гра.
 *
 * ## Що ловить цей файл
 *
 * Скарга автора: в онлайні хід за межі дошки натискається й не робиться, і гра не
 * завершується — а в соло й у місцевій грі завершується. Причина була не в
 * правилі, а в тому, що онлайн ходив ІНШИМ шляхом: `BaseGameMode` питає рушій і
 * на відмову йде в `onPlayerMoveFailure` (фігура вилітає за край, партія
 * закінчується), а `OnlineGameMode` рушія не питав узагалі — дописував хід у
 * журнал, а перепрогін його потім відкидав. Відкинутий хід не означає нічого:
 * дошка стоїть, черга не йде, партія триває вічно.
 *
 * ## Чому перевірка саме така
 *
 * Це перевірка ФОРМИ виклику, а не поведінки: режими гри тримаються на десятку
 * синглтонів (сторі, сервіс завершення, шина подій, синк), і підставити їх усі
 * означало б перевіряти власні підставки. Тому тут стверджується рівно те, чого
 * бракувало: рушій опитується ДО запису в журнал, а відмова йде спільним шляхом.
 *
 * Саму поведінку заміряно в браузері вдвох (емулятор, дві незалежні сесії):
 * фігура на [0,0] дошки 2×2, хід «вгору» — обидва гравці бачать «Гра завершена».
 *
 * Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1): прибрати виклик
 * `performMove` з `handlePlayerMove` — обидві перевірки нижче червоніють.
 */

const FILE = 'src/lib/game-modes/OnlineGameMode.ts';

/** Тіло `handlePlayerMove` — від його оголошення до наступного методу. */
function movePath(): string {
	const text = readFileSync(FILE, 'utf8');
	const from = text.indexOf('async handlePlayerMove(');
	expect(from, `у ${FILE} немає handlePlayerMove — перевірка дивиться не туди`).toBeGreaterThan(-1);
	// Межа — наступний метод. Перенос рядка через код символу: у літералі він
	// перетворився б на справжній перенос і зламав би сам файл перевірки.
	const nextMethod = String.fromCharCode(10) + '  async ';
	const to = text.indexOf(nextMethod, from + 10);
	return text.slice(from, to === -1 ? undefined : to);
}

describe('онлайн-хід перевіряється рушієм', () => {
	it('рушій опитується ДО запису в журнал', () => {
		const body = movePath();
		const asked = body.indexOf('performMove');
		const written = body.indexOf('appendMove');

		expect(asked, 'без `performMove` неможливий хід тихо зникає в журналі').toBeGreaterThan(-1);
		expect(written, 'хід мусить дописуватися в журнал').toBeGreaterThan(-1);
		expect(
			asked,
			'порядок тут — частина правила: записаний хід уже не скасувати, правила не дають стерти документ'
		).toBeLessThan(written);
	});

	it('відмова йде тим самим шляхом, що в місцевій грі', () => {
		// Саме ВИКЛИК, а не згадка: коментарі поруч називають цей метод, і перевірка
		// на просту назву лишалася б зеленою, якби код прибрали, а коментар — ні.
		expect(
			movePath(),
			'`onPlayerMoveFailure` з `BaseGameMode` — це і є «фігура вилітає за край, партія закінчується»'
		).toContain('this.onPlayerMoveFailure(');
	});
});
